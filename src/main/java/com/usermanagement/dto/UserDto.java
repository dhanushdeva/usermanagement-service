package com.usermanagement.dto;

import java.util.List;

import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonProperty;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Getter
@Setter
@NoArgsConstructor
@JsonInclude(JsonInclude.Include.NON_NULL)
@Schema(description = "A user stored in Keycloak")
public class UserDto {

    @Schema(description = "Generated by Keycloak; required only for update")
    private String userId;

    @Schema(description = "Login name")
    private String userName;

    @Schema(description = "Initial password (never returned in responses)", accessMode = Schema.AccessMode.WRITE_ONLY)
    @JsonProperty(access = JsonProperty.Access.WRITE_ONLY)
    private String password;

    private String firstName;
    private String lastName;
    private String email;

    @Schema(description = "Keycloak realm role names")
    private List<String> roles;

    @Schema(description = "Stored as user attribute entity_type, e.g. CUSTOMER, AGENT")
    private String entityType;

    @Schema(description = "Stored as user attribute entity_id")
    private String entityId;

    @Schema(description = "Any other user attributes")
    private List<AttributeDto> additionalAttributes;

    @Schema(description = "ENABLE or DISABLE (defaults to ENABLE on register)")
    private String status;
}
