package com.usermanagement.dto;

import java.io.Serializable;
import java.util.List;

import io.swagger.v3.oas.annotations.media.ArraySchema;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

@Getter
@Setter
@NoArgsConstructor
@Schema(name = "User", description = "Details about the user, using authentication and personal information")
public class User implements Serializable {

    private static final long serialVersionUID = 1L;

    @Schema(description = "User Id is generated by the identity provider and not required in the request")
    private String userId;
    @Schema(description = "User Name that is used for registration and authentication")
    private String userName;
    @Schema(description = "Password that is used for registration and authentication")
    private String password;
    @Schema(description = "First name of the user")
    private String firstName;
    @Schema(description = "Last name of the user")
    private String lastName;
    @Schema(description = "Email address of the user", example = "john.doe@example.com")
    private String email;
    @ArraySchema(schema = @Schema(description = "A roles/permissions that the user has"),
            arraySchema = @Schema(description = "A list of roles/permissions that the user has"))
    private List<String> roles;
    @Schema(description = "This could be either CUSTOMER_ID or AGENT_ID or ADMIN_ID etc. This is used to identify "
            + "the user in the underlying systems.")
    private String entityType;
    @Schema(description = "The value of the entity type")
    private String entityId;
    @Schema(description = "Any other additional attributes of the user")
    private Attribute[] additionalAttributes;
    @Schema(description = "Status of the user, either ENABLE or DISABLE in upper case",
            allowableValues = {"ENABLE", "DISABLE"}, example = "ENABLE")
    private String status;
}
